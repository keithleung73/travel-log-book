export function defaultLeadingTeachers(): LeadingTeacher[] {
  return SCHOOL_TEACHERS_GO007.map((teacher) => ({ ...teacher }));
}

export function teacherLabel(teacher: LeadingTeacher): string {
  return teacher.classCode ? `${teacher.name}（${teacher.classCode}）` : teacher.name;
}

export function sortTeachers(teachers: LeadingTeacher[]): LeadingTeacher[] {
  const rank = (code?: string) => {
    if (!code) return 1000;
    const index = CLASS_TEACHER_ORDER.indexOf(code as (typeof CLASS_TEACHER_ORDER)[number]);
    return index >= 0 ? index : 500;
  };
  return teachers.slice().sort((a, b) => {
    const byClass = rank(a.classCode) - rank(b.classCode);
    if (byClass !== 0) return byClass;
    return a.name.localeCompare(b.name, "zh-HK");
  });
}

export function groupTeachers(teachers: LeadingTeacher[]): Array<{
  key: string;
  heading: string;
  teachers: LeadingTeacher[];
}> {
  const byClass = new Map<string, LeadingTeacher[]>();
  const others: LeadingTeacher[] = [];
  for (const teacher of teachers) {
    if (teacher.classCode) {
      const list = byClass.get(teacher.classCode) ?? [];
      list.push(teacher);
      byClass.set(teacher.classCode, list);
    } else {
      others.push(teacher);
    }
  }
  const groups: Array<{ key: string; heading: string; teachers: LeadingTeacher[] }> = [];
  for (const code of CLASS_TEACHER_ORDER) {
    const list = byClass.get(code);
    if (list?.length) groups.push({ key: code, heading: `${code} 班主任`, teachers: list });
  }
  for (const [code, list] of byClass) {
    if (!(CLASS_TEACHER_ORDER as readonly string[]).includes(code)) {
      groups.push({ key: code, heading: `${code} 班主任`, teachers: list });
    }
  }
  if (others.length) groups.push({ key: "other", heading: "其他老師", teachers: others });
  return groups;
}
